const assert=require('node:assert/strict');
const fs=require('node:fs');
const path=require('node:path');
const vm=require('node:vm');
const ts=require('typescript');
const React=require('react');
const {renderToStaticMarkup}=require('react-dom/server');
const root=path.resolve(__dirname,'../src');
function load(file){
 if(file.endsWith('.css'))return {default:new Proxy({}, {get:(_,key)=>String(key)})};
 if(!path.extname(file))file+=fs.existsSync(file+'.tsx')?'.tsx':'.ts';
 const module={exports:{}};
 const requireModule=name=>name.startsWith('.')?load(path.resolve(path.dirname(file),name)):name.startsWith('@/')?load(path.join(root,name.slice(2))):require(name);
 vm.runInNewContext(ts.transpileModule(fs.readFileSync(file,'utf8'),{compilerOptions:{target:ts.ScriptTarget.ES2020,module:ts.ModuleKind.CommonJS,jsx:ts.JsxEmit.ReactJSX}}).outputText,{exports:module.exports,module,require:requireModule,process,console});
 return module.exports;
}
const {cupMatches,belongsToTeam,matchdayOrder,hasPlayoffs}=load(path.join(root,'lib/matchday.ts'));
const matches=[{id:1,scheduled_start:'2026-10-24T08:30',match_status:'finished',home_score:0,away_score:2},{id:2,scheduled_start:'2026-10-24T09:00',match_status:'live'},{id:3,scheduled_start:'2026-10-24T10:00',match_status:'not_started'}];
const cup={tournament:{arrangement_type:'tournament'},matches,brackets:[{matches:[matches[2],{id:4,home_source:'team:9'}]}]};
assert.equal(cupMatches(cup).length,4,'Do not duplicate playoff matches');
assert.equal(matchdayOrder(matches).map(m=>m.id).join(','),'2,3,1','Live first, upcoming next, latest results last');
assert(belongsToTeam({home_participant:{resolved:true,team_id:9}},9),'Resolved playoff source belongs to team');
assert(belongsToTeam({away_source:'team:9'},9));
assert(!belongsToTeam({away_source:'group:9:1'},9),'Do not confuse group IDs and team IDs');
assert(hasPlayoffs({...cup,brackets:[],placement_groups:[{name:'Guld'}]}));
assert(!hasPlayoffs({...cup,tournament:{arrangement_type:'matchcamp'}}));
const {MatchCard}=load(path.join(root,'components/MatchCard.tsx'));
const team={id:9,name:'Fotbollsföreningen med ett riktigt långt namn',primary_color:'#112233',secondary_color:'#aabbcc'};
const props={match:{id:1,home_source:'team:9',away_source:'team:9'},teams:[team],index:0,showLogos:false};
const home=renderToStaticMarkup(React.createElement(MatchCard,{...props,showKits:true,showAwayKits:false}));
assert(home.includes('#112233'));assert(!home.includes('#aabbcc'),'Home-only mode must never render away colours');
const none=renderToStaticMarkup(React.createElement(MatchCard,{...props,showKits:false}));
assert(!none.includes('<svg'),'No shirts means no shirt SVGs');
assert(none.includes(team.name));
